#!/usr/bin/env bash
# Generate /etc/nixos/nas-private.nix (the private values of nas.nix, outside the repository) : the Tailscale address of
# the NAS and its shares, found automatically. Run once per machine, with tailscale on and the NAS reachable, then
# update_config.sh.
# Usage : sh nixos/nas_setup.sh <tailscale name of the NAS> [mount point, /mnt/nas by default]
set -e

name="$1"
mount_point="${2:-/mnt/nas}"
private_file="/etc/nixos/nas-private.nix"
flake_dir="$(cd "$(dirname "$0")" && pwd)"

if [ -z "$name" ]; then
    echo "Usage : $0 <tailscale name of the NAS> [mount point]"
    echo "The machines of the tailnet :"
    tailscale status | awk '{ print "  " $2 }'
    exit 1
fi

address=$(tailscale ip -4 "$name")
echo "NAS $name : $address"

# the shares of the NAS (smbclient from the nixpkgs of this configuration), without the hidden ones (IPC$...)
shares=$(nix shell --impure "$flake_dir#nixosConfigurations.nixos.pkgs.samba" --command \
    smbclient --no-pass --grepable --list "//$address" 2>/dev/null \
    | awk -F'|' '$1 == "Disk" && $2 !~ /\$$/ { print $2 }')
if [ -z "$shares" ]; then
    echo "Error : no share found on //$address (is the NAS on, and tailscale up ?)"
    exit 1
fi
echo "Shares : $(echo $shares)"

{
    echo "# generated by nixos/nas_setup.sh : the private values of nixos/nas.nix (not in the repository)"
    echo "{"
    echo "  address = \"$address\";"
    echo "  mountPoint = \"$mount_point\";"
    echo "  shares = [ $(for share in $shares; do printf '"%s" ' "$share"; done)];"
    echo "}"
} | sudo tee "$private_file" > /dev/null

echo "Written in $private_file, apply it with : sh $flake_dir/update_config.sh"
